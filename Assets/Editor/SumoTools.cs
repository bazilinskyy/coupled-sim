using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;
using UnityStandardAssets.Utility;

/// <summary>
/// Exports Unity lanes (WaypointCircuits) as a SUMO network, so SUMO traffic drives on the roads of
/// a hand-built scene, and builds the SumoTraffic example experiment.
/// SUMO coordinates are Unity's x and z (SumoBridge.NetworkOrigin empty), which needs
/// netconvert's --offset.disable-normalization.
/// </summary>
public static class SumoTools
{
    static string F(float v) => v.ToString("0.###", CultureInfo.InvariantCulture);

    /// <summary>
    /// Writes {name}.nod.xml, {name}.edg.xml, {name}.rou.xml and {name}.sumocfg to `dir`.
    /// Every lane becomes a chain of single-lane edges and a route that loops it; `vehiclesPerHour`
    /// sets the flow on each lane. Build the network with:
    /// netconvert -n name.nod.xml -e name.edg.xml -o name.net.xml --offset.disable-normalization --no-turnarounds
    /// </summary>
    public static void ExportLanes(IList<WaypointCircuit> lanes, string dir, string name, float speedLimit = 13.89f, float vehiclesPerHour = 300f, int simulationSeconds = 3600)
    {
        Directory.CreateDirectory(dir);
        var nodes = new StringBuilder("<nodes>\n");
        var edges = new StringBuilder("<edges>\n");
        var routes = new StringBuilder("<routes>\n  <vType id=\"car\" vClass=\"passenger\" length=\"4.5\" accel=\"2.6\" decel=\"4.5\" sigma=\"0.5\" color=\"0.8,0.8,0.8\"/>\n");
        for (int l = 0; l < lanes.Count; l++)
        {
            var pts = lanes[l].Waypoints.Select(w => w.position).ToList();
            var edgeIds = new List<string>();
            for (int i = 0; i < pts.Count; i++)
                nodes.Append($"  <node id=\"l{l}n{i}\" x=\"{F(pts[i].x)}\" y=\"{F(pts[i].z)}\"/>\n");
            for (int i = 0; i < pts.Count; i++)
            {
                var id = $"l{l}e{i}";
                edgeIds.Add(id);
                edges.Append($"  <edge id=\"{id}\" from=\"l{l}n{i}\" to=\"l{l}n{(i + 1) % pts.Count}\" numLanes=\"1\" speed=\"{F(speedLimit)}\" spreadType=\"center\"/>\n");
            }
            routes.Append($"  <route id=\"lane{l}\" edges=\"{string.Join(" ", edgeIds)}\" repeat=\"100\"/>\n");
            routes.Append($"  <flow id=\"flow{l}\" type=\"car\" route=\"lane{l}\" begin=\"0\" end=\"{simulationSeconds}\" vehsPerHour=\"{F(vehiclesPerHour)}\" departLane=\"best\" departSpeed=\"max\" departPos=\"random_free\"/>\n");
        }
        nodes.Append("</nodes>\n");
        edges.Append("</edges>\n");
        routes.Append("</routes>\n");
        File.WriteAllText(Path.Combine(dir, name + ".nod.xml"), nodes.ToString());
        File.WriteAllText(Path.Combine(dir, name + ".edg.xml"), edges.ToString());
        File.WriteAllText(Path.Combine(dir, name + ".rou.xml"), routes.ToString());
        File.WriteAllText(Path.Combine(dir, name + ".sumocfg"),
$@"<configuration>
  <input>
    <net-file value=""{name}.net.xml""/>
    <route-files value=""{name}.rou.xml""/>
  </input>
  <time>
    <step-length value=""0.05""/>
  </time>
  <processing>
    <ignore-route-errors value=""true""/>
    <time-to-teleport value=""-1""/>
  </processing>
</configuration>
");
        File.WriteAllText(Path.Combine(dir, "README.md"),
$@"# SUMO scenario `{name}`

Generated by `SumoTools.ExportLanes` from the scene's lanes. SUMO coordinates are Unity x/z.
Rebuild the network after changing the lanes:

    netconvert -n {name}.nod.xml -e {name}.edg.xml -o {name}.net.xml --offset.disable-normalization --no-turnarounds
");
    }

    const string ExamplePath = "Assets/ExperimentDefinitions/SumoTraffic.prefab";
    const string ScenarioDir = "Assets/StreamingAssets/Sumo/MainScene";

    /// <summary>
    /// Example: Base with SUMO traffic in both directions around the central block of MainScene.
    /// Writes the SUMO scenario to StreamingAssets/Sumo/MainScene (build its network with netconvert).
    /// </summary>
    [MenuItem("Coupled Sim/Examples/Create SumoTraffic experiment")]
    public static void CreateExample()
    {
        var cars = new[] { "Assets/Prefabs/Cars/DrivableSmartCommon.prefab", "Assets/Prefabs/Cars/DrivableHatchbackCommon.prefab" }
            .Select(p => AssetDatabase.LoadAssetAtPath<GameObject>(p)?.GetComponent<AICar>()).Where(c => c != null).ToArray();
        TrafficTools.RegisterAICarPrefabs(cars);

        if (AssetDatabase.LoadAssetAtPath<GameObject>(ExamplePath) == null)
            AssetDatabase.CopyAsset("Assets/ExperimentDefinitions/Base.prefab", ExamplePath);
        var root = PrefabUtility.LoadPrefabContents(ExamplePath);
        try
        {
            var exp = root.GetComponent<ExperimentDefinition>();
            exp.Name = "SUMO traffic";
            exp.ShortName = "Sumo";
            var old = root.transform.Find("SUMO");
            if (old != null) Object.DestroyImmediate(old.gameObject);
            var sumo = new GameObject("SUMO").transform;
            sumo.SetParent(root.transform, false);
            var inner = root.GetComponentsInChildren<WaypointCircuit>(true).First(c => c.name == "Passenger Traffic Circuit");
            var outer = TrafficTools.CreateOppositeLane(inner, sumo, "Opposite lane", 5f);
            ExportLanes(new[] { inner, outer }, ScenarioDir, "mainscene", vehiclesPerHour: 240);

            var bridge = sumo.gameObject.AddComponent<SumoBridge>();
            bridge.SumoConfig = "Sumo/MainScene/mainscene.sumocfg";
            bridge.CarPrefabs = cars;
            bridge.spawnParams = new CarSpawnParams { Car = cars[0], SpawnDriver = true, VehicleType = PlayerSystem.VehicleType.MDV };
            exp.CarSpawners = exp.CarSpawners.Where(s => s != null).Append(bridge).ToArray();
            PrefabUtility.SaveAsPrefabAsset(root, ExamplePath);
        }
        finally
        {
            PrefabUtility.UnloadPrefabContents(root);
        }
        ExperimentPedestrianTools.RegisterInStartScene(ExamplePath);
        AssetDatabase.Refresh();
        Debug.Log("Created " + ExamplePath);
    }
}
